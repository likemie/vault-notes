def external_collisions(items: list[ArgumentCitation]) -> dict[str, Any]:
    """Works outside the vault (currently Visible Learning MetaX) whose first author
    and year equal an Argument's but whose title differs. They must never be linked
    to that Argument by author-year; see scripts/metax_sync.py."""
    if not METAX_JSON.exists():
        return {}
    try:
        studies = json.loads(METAX_JSON.read_text(encoding="utf-8")).get("studies", {})
    except (OSError, ValueError):
        return {}
    by_target = {item.target: item for item in items}
    out: dict[str, Any] = {}
    for sid, st in sorted(studies.items()):
        if st.get("match") not in {"collision", "review"}:
            continue
        item = by_target.get(st.get("collides_with", ""))
        if item is None:
            continue
        out.setdefault(item.base_key, {"argument": item.target, "aliases": item.aliases, "external": []})["external"].append({
            "source": "metax",
            "id": sid,
            "status": st["match"],
            "apa": st.get("apa", ""),
            "authors": st.get("authors_raw", ""),
            "year": st.get("year", ""),
            "title": st.get("title", ""),
        })
    return out


def write_json(full: dict[str, Any], ambiguous: dict[str, Any], dry_run: bool) -> None:
    outputs = {
        FULL_JSON: json.dumps(full, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        AMBIG_JSON: json.dumps(ambiguous, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
    }
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if dry_run:
            print(f"[dry-run] would write {path.relative_to(ROOT)}")
            continue
        CITATION_DIR.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"✅ wrote {path.relative_to(ROOT)}")


def check(items: list[ArgumentCitation]) -> int:
    errors = 0
    seen: dict[str, list[str]] = {}
    for item in items:
        if not isinstance(item.citation, str) or not item.citation.strip():
            print(f"❌ citation-eligible Argument missing full citation: {item.rel_path}")
            errors += 1
        for alias in item.aliases:
            seen.setdefault(alias, []).append(item.rel_path)
    for alias, paths in seen.items():
        if len(paths) > 1:
            print(f"❌ duplicate citation alias {alias!r}: " + ", ".join(paths))
            errors += 1
    return errors


def check_inherited_chapters(chapters: list[InheritedBookChapter]) -> int:
    errors = 0
    for chapter in chapters:
        if chapter.aliases:
            print(f"❌ inherited book chapter should not have citation_aliases: {chapter.rel_path} aliases={chapter.aliases}")
            errors += 1
        expected_part_of = f"[[{chapter.parent_target}]]"
        if chapter.current_part_of != expected_part_of:
            print(f"❌ inherited book chapter part_of should be {expected_part_of}: {chapter.rel_path} got={chapter.current_part_of!r}")
            errors += 1
    return errors



