"""
citation_index.py

Maintain Argument citation aliases and generated citation JSON indexes.

Default behavior:
  1. Scan citation-eligible Argument pages.
  2. Generate expected citation_aliases from authors + year.
  3. Remove legacy citation_stem/citation_suffix/citation_key/citation_short.
  4. Write citation/citation_full.json and citation/citation_ambiguous.json
     (same author-year groups with their APA 7 disambiguation rule, plus
     external author-year collisions recorded by scripts/metax_sync.py).
  5. Collect unlinked short citations into citation/external_identities.json
     and write citation/citation_external.json. MetaX collisions are not
     part of that collection. --check does not scan or write those files.

This script does not link body text. Use scripts/wiki_linker.py sync --citations-only for that.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
WIKI_DIR = ROOT / "wiki"
ARG_DIR = WIKI_DIR / "arguments"
CITATION_DIR = ROOT / "citation"
FULL_JSON = CITATION_DIR / "citation_full.json"
AMBIG_JSON = CITATION_DIR / "citation_ambiguous.json"

FRONTMATTER_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.S)
KEY_RE = re.compile(r"^([A-Za-z0-9_-]+):\s*(.*)$")
LEGACY_FIELDS = {"citation_stem", "citation_suffix", "citation_key", "citation_short"}
GENERATED_NOTE = "Generated by scripts/citation_index.py. Do not edit manually."


# Journal naming is part of citation maintenance.
REGISTRY = ROOT / "citation/journals.json"
ARTICLES = ROOT / "wiki/arguments/journal-articles"


def name_key(value: str) -> str:
    return unicodedata.normalize("NFC", value).casefold()


def unique_pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate journal name: {key!r}")
        result[key] = value
    return result


def load_registry(path: Path | None = None) -> dict[str, str]:
    data = json.loads((path or REGISTRY).read_text(encoding="utf-8"), object_pairs_hook=unique_pairs)
    if not isinstance(data, dict):
        raise ValueError("journal registry must be a journal-name to code mapping")
    names, codes = set(), {}
    for journal, code in data.items():
        if not journal.strip() or journal != journal.strip() or name_key(journal) in names:
            raise ValueError(f"invalid or duplicate journal name: {journal!r}")
        if not isinstance(code, str) or not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", code):
            raise ValueError(f"invalid journal code for {journal!r}: {code!r}")
        if code.casefold() in codes:
            raise ValueError(f"journal code {code!r} is shared by {codes[code.casefold()]!r} and {journal!r}")
        names.add(name_key(journal))
        codes[code.casefold()] = journal
    return data


def journal_metadata(text: str) -> dict:
    match = re.match(r"\A---\r?\n(.*?)\r?\n---(?:\r?\n|$)", text, re.S)
    data = yaml.safe_load(match.group(1)) if match else None
    return data if isinstance(data, dict) else {}


def article_problem(path: Path, meta: dict, registry: dict[str, str]) -> str | None:
    journal = str(meta.get("journal") or "").strip()
    if not journal:
        return "journal full name is missing"
    code = registry.get(journal)
    if code is None:
        return f"journal is not registered in citation/journals.json: {journal!r}"
    if not re.fullmatch(r"Argument_.+_(?:19|20)\d{2}[a-z]?_" + re.escape(code), path.stem):
        return f"journal filename must end in _<Year>_{code}: {journal!r}"
    return None


def is_legacy(path: Path, meta: dict, base: str | None = None) -> bool:
    """Grandfather an unchanged journal/name pair, never a new or renamed path."""
    ref = base or os.environ.get("VAULT_JOURNAL_BASE") or "HEAD"
    if set(ref) == {"0"}:
        return False
    try:
        relative = path.relative_to(ROOT).as_posix()
        result = subprocess.run(["git", "show", f"{ref}:{relative}"], cwd=ROOT,
                                capture_output=True, text=True)
        return result.returncode == 0 and str(journal_metadata(result.stdout).get("journal") or "").strip() == str(meta.get("journal") or "").strip()
    except (ValueError, OSError, yaml.YAMLError):
        return False


def check_articles(registry: dict[str, str], base: str | None = None) -> list[str]:
    errors = []
    for path in sorted(ARTICLES.rglob("*.md")):
        if path.name == "index.md":
            continue
        meta = journal_metadata(path.read_text(encoding="utf-8"))
        if meta.get("type") != "argument":
            continue
        problem = article_problem(path, meta, registry)
        if problem and not is_legacy(path, meta, base):
            errors.append(f"{path.relative_to(ROOT)}: {problem}")
    return errors

def run_journal_registry(register: list[str] | None = None, base: str | None = None) -> int:
    """Validate journal naming, optionally registering an explicit code first."""
    try:
        registry = load_registry()
        if register:
            journal, code = register
            if journal in registry and registry[journal] != code:
                raise ValueError(f"journal already registered as {registry[journal]!r}; changing it requires a naming review")
            registry[journal] = code
            # Validate the proposed table before replacing the authoritative file.
            encoded = json.dumps(dict(sorted(registry.items())), ensure_ascii=False, separators=(",", ":")) + "\n"
            proposed = REGISTRY.with_suffix(".json.tmp")
            try:
                proposed.write_text(encoded, encoding="utf-8")
                load_registry(proposed)
                proposed.replace(REGISTRY)
            finally:
                proposed.unlink(missing_ok=True)
        errors = check_articles(registry, base=base)
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f"Journal registry error: {exc}")
        return 1
    for error in errors:
        print(f"Journal naming error: {error}")
    print(f"Journal registry: {len(registry)} journals; {len(errors)} error(s).")
    return int(bool(errors))


@dataclass
class ArgumentCitation:
    path: Path
    title: str
    authors: list[str]
    year: str
    doi: str
    isbn: str
    citation: str
    source_language: str
    base_aliases: list[str]
    aliases: list[str]
    rule: str = ""
    apa7_aliases: list[str] = field(default_factory=list)

    @property
    def rel_path(self) -> str:
        return self.path.relative_to(ROOT).as_posix()

    @property
    def target(self) -> str:
        return self.path.stem

    @property
    def base_key(self) -> str:
        return self.base_aliases[0]

    def json_entry(self) -> dict[str, Any]:
        return {
            "argument": self.target,
            "path": self.rel_path,
            "aliases": self.aliases,
            "year": self.year,
            "doi": self.doi,
            "isbn": self.isbn,
            "authors": self.authors,
            "citation": self.citation,
            "source_language": self.source_language,
            "title": self.title,
        }


@dataclass
class InheritedBookChapter:
    path: Path
    title: str
    aliases: list[str]
    parent_target: str
    current_part_of: str

    @property
    def rel_path(self) -> str:
        return self.path.relative_to(ROOT).as_posix()


def parse_scalar(value: str) -> str:
    value = value.strip()
    if value in {"", "null", "None", "~"}:
        return ""
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
        inner = value[1:-1]
        return inner.replace("''", "'") if value[0] == "'" else inner
    return value


def parse_inline_list(value: str) -> list[str]:
    inner = value[1:-1].strip()
    if not inner:
        return []
    items: list[str] = []
    current = ""
    quote = ""
    for ch in inner:
        if ch in {"'", '"'}:
            quote = "" if quote == ch else ch if not quote else quote
            current += ch
        elif ch == "," and not quote:
            items.append(parse_scalar(current))
            current = ""
        else:
            current += ch
    if current.strip():
        items.append(parse_scalar(current))
    return [x for x in items if x]


def parse_frontmatter(text: str) -> tuple[dict[str, Any], str, str]:
    m = FRONTMATTER_RE.match(text)
    if not m:
        return {}, "", text
    raw = m.group(1)
    body = text[m.end():]
    data: dict[str, Any] = {}
    lines = raw.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        m_key = KEY_RE.match(line)
        if not m_key:
            i += 1
            continue
        key, val = m_key.group(1), m_key.group(2).strip()
        if val == "":
            items: list[str] = []
            j = i + 1
            while j < len(lines) and re.match(r"^\s*-\s+", lines[j]):
                items.append(parse_scalar(re.sub(r"^\s*-\s+", "", lines[j])))
                j += 1
            data[key] = items if items else ""
            i = j
            continue
        if val.startswith("[") and val.endswith("]"):
            data[key] = parse_inline_list(val)
        else:
            data[key] = parse_scalar(val)
        i += 1
    return data, raw, body


def list_value(value: Any) -> list[str]:
    if isinstance(value, list):
        return [str(x).strip() for x in value if str(x).strip()]
    if isinstance(value, str) and value.strip():
        return [value.strip()]
    return []


def display_from_wikilink(value: str) -> str:
    m = re.fullmatch(r"\[\[([^|\]]+)(?:\|([^\]]+))?\]\]", value.strip())
    if not m:
        return value.strip()
    return (m.group(2) or m.group(1)).strip()


def target_from_wikilink(value: str) -> str:
    m = re.fullmatch(r"\[\[([^|\]]+)(?:\|([^\]]+))?\]\]", value.strip())
    if not m:
        return ""
    return m.group(1).strip()


def author_label(author: str) -> str:
    author = display_from_wikilink(author)
    author = author.replace("''", "'")
    author = re.sub(r"\s+", " ", author).strip()
    if "," in author:
        return author.split(",", 1)[0].strip()
    return author


def author_part(authors: list[str]) -> str:
    labels = [author_label(a) for a in authors if author_label(a)]
    if not labels:
        return ""
    if len(labels) == 1:
        return labels[0]
    if len(labels) == 2:
        return f"{labels[0]} & {labels[1]}"
    return f"{labels[0]} et al."


def has_cjk(text: str) -> bool:
    return bool(re.search(r"[\u3400-\u9fff]", text))


def dedupe(items: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for item in items:
        if item and item not in seen:
            result.append(item)
            seen.add(item)
    return result


def chinese_author_part(citation: str, year: str) -> str:
    if not has_cjk(citation) or not year:
        return ""
    m = re.match(rf"^\s*(?P<authors>.+?)\s*(?:[.。]\s*)?[（(]\s*{re.escape(year)}\s*[）)]", citation)
    if not m:
        return ""
    raw = m.group("authors").strip(" ,，.。")
    if not has_cjk(raw):
        return ""
    parts = [p.strip() for p in re.split(r"[、，,；;]\s*", raw) if p.strip()]
    cjk_parts = [p for p in parts if has_cjk(p)]
    if not cjk_parts:
        return ""
    if len(cjk_parts) == 1:
        return cjk_parts[0]
    if len(cjk_parts) == 2:
        return f"{cjk_parts[0]}和{cjk_parts[1]}"
    return f"{cjk_parts[0]}等"


def normalized_source_language(value: Any) -> str:
    language = str(value or "").strip().lower().replace("_", "-")
    if language in {"zh", "zh-cn", "zh-hans", "chinese", "中文"}:
        return "zh"
    if language in {"en", "en-us", "en-gb", "english", "英文"}:
        return "en"
    return language


def source_language_for(meta: dict[str, Any]) -> str:
    explicit = normalized_source_language(meta.get("source_language"))
    if explicit:
        return explicit
    citation = str(meta.get("citation") or "").strip()
    year = str(meta.get("year") or "").strip()
    return "zh" if chinese_author_part(citation, year) else "en"


def aliases_for_parts(parts: list[str], year: str) -> list[str]:
    if not parts or not year:
        return []
    aliases: list[str] = []
    for part in parts:
        aliases.extend([f"{part}, {year}", f"{part} ({year})"])
    return dedupe(aliases)


def aliases_for(authors: list[str], year: str, citation: str = "", source_language: str = "") -> list[str]:
    base_year = re.sub(r"[a-z]$", "", year)
    chinese_part = chinese_author_part(citation, base_year)
    if normalized_source_language(source_language) == "zh" or chinese_part:
        parts = [chinese_part] if chinese_part else []
    else:
        parts = [author_part(authors)]
    parts = [p for p in dedupe(parts) if p]
    return aliases_for_parts(parts, year)


def is_citation_eligible(meta: dict[str, Any], path: Path) -> bool:
    if meta.get("type") != "argument":
        return False
    if meta.get("subtype") == "edited-volume-overview":
        return False
    if inherited_book_chapter_parent(meta, path):
        return False
    if "templates" in path.parts:
        return False
    return bool(str(meta.get("year") or "").strip() and list_value(meta.get("authors")))


def inferred_parent_target_from_filename(path: Path) -> str:
    m = re.match(r"^(Argument_.+)_Ch\d{1,3}(?:[_-].+)?$", path.stem)
    if not m:
        return ""
    parent_target = m.group(1)
    parent_path = path.with_name(f"{parent_target}.md")
    return parent_target if parent_path.exists() else ""


def inherited_book_chapter_parent(meta: dict[str, Any], path: Path) -> str:
    """Chapter Argument for a single authored book; cite the parent book instead."""
    if meta.get("publication_type") != "book-chapter":
        return ""
    if meta.get("subtype") not in {"textbook", "monograph"}:
        return ""
    part_of = str(meta.get("part_of") or "").strip()
    if part_of.startswith("[[Argument_") and part_of.endswith("]]"):
        return target_from_wikilink(part_of)
    return inferred_parent_target_from_filename(path)


def load_arguments() -> tuple[list[ArgumentCitation], list[InheritedBookChapter]]:
    items: list[ArgumentCitation] = []
    inherited_chapters: list[InheritedBookChapter] = []
    if not ARG_DIR.exists():
        return items, inherited_chapters
    for path in sorted(ARG_DIR.rglob("*.md")):
        text = path.read_text(encoding="utf-8", errors="replace")
        meta, _, _ = parse_frontmatter(text)
        parent_target = inherited_book_chapter_parent(meta, path)
        if parent_target:
            inherited_chapters.append(InheritedBookChapter(
                path=path,
                title=str(meta.get("title") or path.stem).strip(),
                aliases=list_value(meta.get("citation_aliases")),
                parent_target=parent_target,
                current_part_of=str(meta.get("part_of") or "").strip(),
            ))
            continue
        if not is_citation_eligible(meta, path):
            continue
        authors = list_value(meta.get("authors"))
        year = str(meta.get("year") or "").strip()
        citation = str(meta.get("citation") or "").strip()
        source_language = source_language_for(meta)
        base = aliases_for(authors, year, citation, source_language)
        if not base:
            continue
        items.append(ArgumentCitation(
            path=path,
            title=str(meta.get("title") or path.stem).strip(),
            authors=authors,
            year=year,
            doi=str(meta.get("doi") or "").strip(),
            isbn=str(meta.get("isbn") or "").strip(),
            citation=citation,
            source_language=source_language,
            base_aliases=base,
            aliases=base,
        ))
    return items, inherited_chapters


# Same-surname / et al. disambiguation (APA 7, 8.18 and 8.20).
#
# Works that share a base short cite ("Zhang et al., 2022") are told apart in
# this order: (1) first authors who are different people with the same surname
# get their initials ("J. Zhang et al."); (2) different co-author lists that
# collapse to the same "et al." form list as many names as needed
# ("Kim, Lee, et al."); (3) only identical author lists fall back to a/b year
# suffixes. The recommended form is always written to citation_ambiguous.json
# (`rule`, `apa7_aliases`). It replaces the a/b suffix in `citation_aliases`
# only when APA7_DISAMBIGUATION is True or `--apa7` is passed, because the
# switch rewrites existing citation displays across the vault.
APA7_DISAMBIGUATION = False


def surname_initials(author: str) -> tuple[str, str]:
    disp = re.sub(r"\s+", " ", display_from_wikilink(author)).strip()
    if "," in disp:
        surname, initials = disp.split(",", 1)
        return surname.strip(), initials.strip()
    return disp, ""


def expanded_part(authors: list[str], shown: int) -> str:
    labels = [author_label(a) for a in authors if author_label(a)]
    if len(labels) <= 2 or shown <= 1:
        return author_part(authors)
    if shown >= len(labels):
        return ", ".join(labels[:-1]) + ", & " + labels[-1]
    return ", ".join(labels[:shown]) + ", et al."


def apa7_plan(group: list[ArgumentCitation]) -> dict[int, tuple[str, str, bool]]:
    """Return {id(item): (author_part, rule, needs_suffix)} for one base-alias group."""
    plan: dict[int, tuple[str, str, bool]] = {}
    if any(item.source_language == "zh" for item in group):
        for item in group:
            plan[id(item)] = (author_part(item.authors), "suffix", True)
        return plan
    by_initials: dict[str, list[ArgumentCitation]] = {}
    for item in group:
        _, initials = surname_initials(item.authors[0]) if item.authors else ("", "")
        by_initials.setdefault(re.sub(r"[\s.]", "", initials).casefold(), []).append(item)
    use_initials = len(by_initials) > 1
    for sub in by_initials.values():
        prefix = ""
        if use_initials and sub[0].authors:
            prefix = surname_initials(sub[0].authors[0])[1] + " "
        rule = "initials" if use_initials else ""
        if len(sub) == 1:
            plan[id(sub[0])] = (prefix + author_part(sub[0].authors), rule or "suffix", False)
            continue
        labels = {id(i): [author_label(a) for a in i.authors if author_label(a)] for i in sub}
        longest = max(len(v) for v in labels.values())
        unresolved = list(sub)
        for shown in range(2, longest + 1):
            buckets: dict[tuple, list[ArgumentCitation]] = {}
            for item in unresolved:
                buckets.setdefault(tuple(labels[id(item)][:shown]), []).append(item)
            still = []
            for members in buckets.values():
                if len(members) == 1 and len(buckets) > 1:
                    item = members[0]
                    plan[id(item)] = (prefix + expanded_part(item.authors, shown), "authors", False)
                else:
                    still.extend(members)
            unresolved = still
            if not unresolved:
                break
        for item in unresolved:
            plan[id(item)] = (prefix + author_part(item.authors), rule or "suffix", True)
    return plan


def assign_suffixes(items: list[ArgumentCitation], apa7: bool | None = None) -> None:
    apa7 = APA7_DISAMBIGUATION if apa7 is None else apa7
    groups: dict[str, list[ArgumentCitation]] = {}
    for item in items:
        groups.setdefault(item.base_key, []).append(item)
    for group in groups.values():
        if len(group) == 1:
            group[0].aliases = group[0].base_aliases
            group[0].rule, group[0].apa7_aliases = "", []
            continue
        ordered = sorted(group, key=lambda x: (x.citation, x.title, x.rel_path))
        plan = apa7_plan(ordered)
        # a/b suffixes are assigned only among works whose recommended part still collides.
        suffix_groups: dict[str, list[ArgumentCitation]] = {}
        for item in ordered:
            part, _, needs = plan[id(item)]
            if needs:
                suffix_groups.setdefault(part, []).append(item)
        suffix_of = {id(i): chr(ord("a") + n) for members in suffix_groups.values() for n, i in enumerate(members)}
        for idx, item in enumerate(ordered):
            part, rule, needs = plan[id(item)]
            item.rule = rule
            item.apa7_aliases = aliases_for_parts([part], f"{item.year}{suffix_of.get(id(item), '')}") if item.source_language != "zh" else []
            if apa7 and item.source_language != "zh":
                item.aliases = item.apa7_aliases
            else:
                suffix = chr(ord("a") + idx)
                item.aliases = aliases_for(item.authors, f"{item.year}{suffix}", item.citation, item.source_language)


def yaml_quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def aliases_block(aliases: list[str]) -> list[str]:
    if not aliases:
        return ["citation_aliases: []"]
    return ["citation_aliases:", *[f"  - {yaml_quote(alias)}" for alias in aliases]]


def replace_frontmatter(text: str, aliases: list[str]) -> str:
    m = FRONTMATTER_RE.match(text)
    if not m:
        return text
    lines = m.group(1).splitlines()
    output: list[str] = []
    inserted = False
    i = 0
    while i < len(lines):
        line = lines[i]
        m_key = KEY_RE.match(line)
        key = m_key.group(1) if m_key else ""
        if key in LEGACY_FIELDS or key == "citation_aliases":
            i += 1
            while i < len(lines) and re.match(r"^\s*-\s+", lines[i]):
                i += 1
            continue
        output.append(line)
        if key == "doi":
            output.extend(aliases_block(aliases))
            inserted = True
        i += 1
    if not inserted:
        insert_at = 0
        for idx, line in enumerate(output):
            m_key = KEY_RE.match(line)
            if m_key and m_key.group(1) in {"year", "citation"}:
                insert_at = idx + 1
        output[insert_at:insert_at] = aliases_block(aliases)
    new_fm = "---\n" + "\n".join(output).rstrip() + "\n---\n"
    return new_fm + text[m.end():]


def replace_scalar_frontmatter_field(text: str, field: str, value: str, after_keys: set[str] | None = None) -> str:
    m = FRONTMATTER_RE.match(text)
    if not m:
        return text
    lines = m.group(1).splitlines()
    output: list[str] = []
    inserted = False
    i = 0
    while i < len(lines):
        line = lines[i]
        m_key = KEY_RE.match(line)
        key = m_key.group(1) if m_key else ""
        if key == field:
            output.append(f"{field}: {yaml_quote(value)}")
            inserted = True
            i += 1
            while i < len(lines) and re.match(r"^\s*-\s+", lines[i]):
                i += 1
            continue
        output.append(line)
        if not inserted and after_keys and key in after_keys:
            next_is_list_item = i + 1 < len(lines) and re.match(r"^\s*-\s+", lines[i + 1])
            if not next_is_list_item:
                output.append(f"{field}: {yaml_quote(value)}")
                inserted = True
        i += 1
    if not inserted:
        output.append(f"{field}: {yaml_quote(value)}")
    new_fm = "---\n" + "\n".join(output).rstrip() + "\n---\n"
    return new_fm + text[m.end():]


def update_argument_files(items: list[ArgumentCitation], dry_run: bool) -> int:
    changed = 0
    for item in items:
        text = item.path.read_text(encoding="utf-8", errors="replace")
        new_text = replace_frontmatter(text, item.aliases)
        if new_text != text:
            changed += 1
            print(f"✏️  {item.rel_path} aliases={item.aliases}")
            if not dry_run:
                item.path.write_text(new_text, encoding="utf-8")
    return changed


def clear_inherited_chapter_aliases(chapters: list[InheritedBookChapter], dry_run: bool) -> int:
    changed = 0
    for chapter in chapters:
        text = chapter.path.read_text(encoding="utf-8", errors="replace")
        new_text = replace_frontmatter(text, [])
        new_text = replace_scalar_frontmatter_field(
            new_text,
            "part_of",
            f"[[{chapter.parent_target}]]",
            after_keys={"sources"},
        )
        if new_text != text:
            changed += 1
            print(f"✏️  {chapter.rel_path} aliases=[] part_of=[[{chapter.parent_target}]]")
            if not dry_run:
                chapter.path.write_text(new_text, encoding="utf-8")
    return changed


def build_indexes(items: list[ArgumentCitation]) -> tuple[dict[str, Any], dict[str, Any]]:
    full: dict[str, Any] = {"_note": GENERATED_NOTE, "items": {}}
    for item in items:
        entry = item.json_entry()
        for alias in item.aliases:
            full["items"][alias] = entry

    ambiguous: dict[str, Any] = {"_note": GENERATED_NOTE, "items": {}}
    groups: dict[str, list[ArgumentCitation]] = {}
    for item in items:
        groups.setdefault(item.base_key, []).append(item)
    for base_key, group in sorted(groups.items()):
        if len(group) > 1:
            ambiguous["items"][base_key] = [
                {**item.json_entry(), "rule": item.rule, "apa7_aliases": item.apa7_aliases}
                for item in sorted(group, key=lambda x: x.aliases[0])
            ]
    external = external_collisions(items)
    if external:
        ambiguous["external"] = external
    return full, ambiguous


